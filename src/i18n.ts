let current: Lang = 'en';
const listeners: Array<(l: Lang) => void> = [];

export function getLang(): Lang {
  return current;
}

export function setLang(l: Lang): void {
  current = l;
  try { localStorage.setItem('terraform_lang', l); } catch { /* ignore */ }
  document.documentElement.lang = l;
  for (const fn of listeners) fn(l);
}

export function initLang(): Lang {
  try {
    const s = localStorage.getItem('terraform_lang');
    if (s === 'en' || s === 'ru') { current = s; return current; }
    current = navigator.language && navigator.language.toLowerCase().startsWith('ru') ? 'ru' : 'en';
  } catch { /* noop */ }
  return current;
}

export function onLangChange(fn: (l: Lang) => void): void {
  listeners.push(fn);
}

export function t(key: string, params?: Record<string, string | number>): string {
  const e = STR[key];
  let s: string;
  if (!e) s = key;
  else s = current === 'ru' ? e.ru : e.en;
  if (params) {
    for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, String(v));
  }
  return s;
}

/** description accessor: def key + '.d' */
export function tdesc(key: string): string {
  return t(`${key}.d`);
}
